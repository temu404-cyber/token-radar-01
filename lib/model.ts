// Token Radar's model (radar-2): one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can rank: the whole
// watchlist (the floor, never the ceiling) plus every other pre-token protocol
// below the floor that is not an exchange and not a versioned pool. Live-token
// protocols are kept apart and shown with the market's own values, never mixed
// into the ranking.
//
// Implied value follows only from the snapshot's own figures, through a peer
// calibration the model computes at run time from the live-token protocols in
// the same snapshot:
//
//   peerMultiple(category) = median(mcap_usd / tvl_usd) over the protocols in
//                            that category whose token already trades, when at
//                            least PEER_MIN of them report both figures;
//                            otherwise the median over every live-token
//                            protocol. Clamped to [PEER_MIN_MULT, PEER_MAX_MULT].
//   growthMult  = 1 + clamp(change_7d, -60, 120) / 100 * GROWTH_WEIGHT
//   maturityMult = 0.6 + min(age_days, 1095) / 1095 * 0.4
//                  (age unknown: 365 days; age is the time since DefiLlama
//                  first listed the protocol, the record of how long it has
//                  run with no token)
//   implied     = max(1, round(tvl_usd * peerMultiple * growthMult * maturityMult))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the peer multiples are recomputed from whatever snapshot is fed in, so a
// different snapshot gives different multiples. The dashboard states the
// formula and prints the peer table it was calibrated from.

/** One protocol entry: exactly the ten fields the sealed snapshot carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants: weights and clamps, never per-protocol values. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  peer_min_count: number;
  peer_min_multiple: number;
  peer_max_multiple: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  peer_min_count: 5,
  peer_min_multiple: 0.05,
  peer_max_multiple: 0.8,
};

